/**
 * 纸纹 — paper fibre over the whole page.
 *
 * Generated by feTurbulence at paint time rather than shipped as an image: the
 * texture keeps up with whatever ink the active theme uses, and it costs one
 * static SVG instead of a request. Kept at 3.5% so it is felt, not seen — at
 * higher opacity it reads as noise on a screen and the text starts to suffer.
 */
export function Grain() {
  return (
    <svg
      aria-hidden='true'
      className='sp-grain pointer-events-none absolute inset-0 -z-10 h-full w-full'
    >
      <filter id='sp-grain-filter'>
        <feTurbulence
          type='fractalNoise'
          baseFrequency='0.82'
          numOctaves='3'
          stitchTiles='stitch'
        />
        <feColorMatrix type='saturate' values='0' />
      </filter>
      <rect width='100%' height='100%' filter='url(#sp-grain-filter)' />
    </svg>
  )
}
